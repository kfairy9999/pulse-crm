// Build an exact asset map from dist/ for the Worker bundle.
// Only /index.html and the public /assets/ allowlist are included.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  SHELL_PATH,
  contentTypeForPath,
  publicAsset,
} from "../src/static-assets.js";

const root = process.cwd();
const dist = path.join(root, "dist");
const outDir = path.join(root, "src", "generated");
const outFile = path.join(outDir, "asset-map.js");
const allowedSkip = new Set(["404.html"]);
const textExtensions = new Set([".html", ".js", ".css", ".svg", ".map"]);
const binaryExtensions = new Set([
  ".png",
  ".jpg",
  ".webp",
  ".ico",
  ".woff2",
]);

async function filesIn(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await filesIn(full)));
    else if (entry.isFile()) found.push(full);
  }
  return found;
}

function pathnameFor(full) {
  const rel = path.relative(dist, full).split(path.sep).join("/");
  if (!rel || rel.startsWith("../") || rel.includes("/../") || rel.includes("\0"))
    throw new Error(`Refusing dist path ${rel || full}`);
  return { rel, pathname: `/${rel}` };
}

const entries = {};
for (const full of await filesIn(dist)) {
  const { rel, pathname } = pathnameFor(full);
  if (rel.endsWith(".map") || rel.includes(".map"))
    throw new Error(
      `Refusing source map ${rel}. Disable build sourcemaps; do not publish them.`,
    );
  const include = pathname === SHELL_PATH || publicAsset(pathname);
  if (!include) {
    if (allowedSkip.has(rel)) continue;
    throw new Error(
      `Refusing to ignore unexpected dist file ${rel}. Add it to the allowlist only if it is a public hashed asset.`,
    );
  }
  const contentType = contentTypeForPath(pathname);
  if (!contentType) throw new Error(`No MIME type for ${pathname}`);
  const ext = path.posix.extname(rel);
  const bytes = await readFile(full);
  if (textExtensions.has(ext)) {
    const body = bytes.toString("utf8");
    if (Buffer.from(body, "utf8").compare(bytes) !== 0)
      throw new Error(`${rel} is not valid UTF-8`);
    entries[pathname] = { contentType, body };
  } else if (binaryExtensions.has(ext)) {
    entries[pathname] = {
      contentType,
      encoding: "base64",
      body: bytes.toString("base64"),
    };
  } else {
    throw new Error(`Unsupported asset extension for ${rel}`);
  }
}

if (!entries[SHELL_PATH]?.body.includes('id="root"'))
  throw new Error("dist/index.html is missing the application root.");
const referenced = [
  ...entries[SHELL_PATH].body.matchAll(/(?:src|href)="(\/[^"]+)"/g),
]
  .map((match) => match[1])
  .filter((item) => item.startsWith("/assets/"));
if (!referenced.some((item) => item.endsWith(".js")))
  throw new Error("dist/index.html does not reference a hashed script.");
for (const item of referenced) {
  if (!publicAsset(item) || !entries[item])
    throw new Error(`Shell references ${item}, which is not an allowlisted asset.`);
}

const ordered = Object.fromEntries(
  Object.keys(entries)
    .sort()
    .map((key) => [key, entries[key]]),
);
await mkdir(outDir, { recursive: true });
await writeFile(
  outFile,
  `// Generated by scripts/generate-asset-map.mjs. Do not edit.\nexport const bundledAssets = ${JSON.stringify(ordered)};\n`,
);
const total = Object.values(ordered).reduce(
  (sum, entry) => sum + Buffer.byteLength(entry.body),
  0,
);
console.log(
  `Generated ${Object.keys(ordered).length} bundled assets (${total} bytes) at src/generated/asset-map.js`,
);
